-- Script 02: secuencias. Ejecutar como AMPAR
CREATE SEQUENCE SEQ_DEPARTAMENTO START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_DEPTO_ID
BEFORE INSERT ON departamento
FOR EACH ROW
WHEN (NEW.id_departamento IS NULL)
BEGIN
    :NEW.id_departamento := SEQ_DEPARTAMENTO.NEXTVAL;
END TRG_DEPTO_ID;
/

